//! The human-facing README and the ownership manifest used for drift detection.

use anyhow::Result;
use espforge_model::{Artifact, Ownership, Project};
use std::collections::BTreeMap;

pub fn owned_paths(artifacts: &[Artifact]) -> Vec<String> {
    artifacts
        .iter()
        .filter(|a| a.ownership == Ownership::Owned)
        .map(|a| a.path.clone())
        .collect()
}

pub fn emit_readme(project: &Project, owned: &[String]) -> String {
    let name = &project.meta.name;
    let owned_list = owned
        .iter()
        .map(|p| format!("  - {p}"))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        r#"espforge generated project: {name}
==========================================

SOURCE OF TRUTH
  This directory is GENERATED from an .espf file. Do not edit the
  machine-owned files below; they are regenerated by every `espforge build`.

EDIT THESE (next to your .espf file, not in this directory):
  - the .espf project file
  - src/app.rs   (your logic: setup/forever; copied here on every build)

MACHINE-OWNED (DO NOT EDIT; regenerated every build):
{owned_list}

REGENERATE:
  espforge build <your.espf> --out <this dir>
"#
    )
}

/// Maps each owned file to a checksum of what espforge wrote.
/// Stored at `.espforge/manifest.json` in the output dir.
pub fn emit_manifest(artifacts: &[Artifact]) -> Result<Artifact> {
    let map: BTreeMap<String, String> = artifacts
        .iter()
        .filter(|a| a.ownership == Ownership::Owned)
        .map(|a| (a.path.clone(), checksum(&a.content)))
        .collect();
    Ok(Artifact::owned(
        ".espforge/manifest.json",
        serde_json::to_string_pretty(&map)?,
    ))
}

/// FNV-1a 64-bit: dependency-free, enough to detect accidental edits.
pub(crate) fn checksum(content: &str) -> String {
    let mut hash: u64 = 0xcbf29ce484222325;
    for b in content.as_bytes() {
        hash ^= *b as u64;
        hash = hash.wrapping_mul(0x100000001b3);
    }
    format!("{hash:016x}")
}
